"""Wrap the exact tested prototype in a marker-guarded private native plugin."""
import argparse,json,struct,subprocess,sys,shutil
from pathlib import Path
HERE=Path(__file__).resolve().parent
sys.path.insert(0,str(HERE.parent/'terrain-prototype'))
from audit import RAW,BASE
import pefile

def main():
 p=argparse.ArgumentParser();p.add_argument('--out',type=Path,required=True);p.add_argument('--compiler',type=Path,required=True);p.add_argument('--qa',action='store_true');a=p.parse_args()
 m=json.loads((a.out/'native/prototype.json').read_text());code=(a.out/'native/prototype.bin').read_bytes();rows=[]
 for h in m['hooks']:
  original=bytes.fromhex(h['before']);rows.append('{'+','.join([str(h['site']),str(h['entry']),str(int(h['kind']=='pointer')),str(len(original)),'{'+','.join(str(v) for v in original)+'}'])+'}')
 source=f'''/* Generated by build_plugin.py from prototype.json/bin. */
static const unsigned char payload[]={{'''+','.join(str(v) for v in code)+'''};
typedef struct {unsigned site,entry,pointer,size;unsigned char before[8];} Hook;
static const Hook hooks[]={'''+','.join(rows)+'''};
typedef struct {unsigned offset;int image,cave;} Fix;
static const Fix fixups[]={'''+','.join('{'+','.join(map(str,f))+'}' for f in m['fixups'])+'''};
'''
 for k,v in {'ALLOCATION':m['size'],'STATE':m['state'],'ROADSTATE':m['roadState'],'UISTATE':m['uiState'],'ADAPTER':m['adapter'],'REQUEST':m['exports']['bridge_request'],'MOVE':m['exports']['bridge_move_request'],'FIELD':m['exports']['bridge_field']}.items():source+=f'#define {k} {v}\n'
 pe=pefile.PE(str(a.out/'native/prototype.dll'))
 ranges=[(s.VirtualAddress,(s.Misc_VirtualSize+4095)&~4095) for s in pe.sections if s.Characteristics&0x20000000]
 ranges.append((m['entry'],m['state']-m['entry']))
 source+='static const unsigned executable[][2]={'+','.join('{'+str(x)+','+str(y)+'}' for x,y in ranges)+'};\n'
 source+=f'#define PREVIEW {m["exports"]["bridge_preview_fixture"]}\n'
 source+=f'#define AUTO_CHECK {m["exports"]["bridge_auto_check"]}\n'
 source+=f'#define ROAD_BIND {m["exports"]["roads_bind"]}\n'
 source+=f'#define MOVE_FIXTURE {m["exports"]["bridge_move_fixture"]}\n'
 source+=f'#define OWNER_REQUEST {m["exports"]["bridge_owner_request"]}\n'
 if 'bridge_art_request' in m['exports']:source+=f'#define ART_REQUEST {m["exports"]["bridge_art_request"]}\n'
 if 'bridge_fixture_offset' in m['exports']:source+=f'#define FIXTURE_FIELD {m["exports"]["bridge_fixture_offset"]}\n'
 source+=f'#define ATTACK_REQUEST {m["exports"]["bridge_attack_request"]}\n'
 source+=f'#define HEALTH_REQUEST {m["exports"]["bridge_health_fixture"]}\n'
 source+=f'#define ACTOR_FIXTURE {m["exports"]["bridge_actor_fixture"]}\n'
 if 'menu_rivers_qa' in m['exports']:source+=f'#define RIVER_MENU {m["exports"]["menu_rivers_qa"]}\n'
 if 'menu_qa_dispatch' in m['exports']:source+=f'#define RIVER_DISPATCH {m["exports"]["menu_qa_dispatch"]}\n'
 if m.get('installed'):source+='#define INSTALLED_RIVERS 1\n'
 if 'menu_settings' in m['exports']:source+=f'#define MAP_SETTINGS {m["exports"]["menu_settings"]}\n'
 (a.out/'native/plugin_data.h').write_text(source)
 destination=a.out/'sandbox/Mods';destination.mkdir(exist_ok=True)
 target=destination/('PawsBridgesQA.dll' if a.qa else 'PawsBridges.dll')
 subprocess.run([str(a.compiler),'-shared','-Wall','-Werror','-I'+str(a.out/'native'),*(['-DPAWS_BRIDGE_QA'] if a.qa else []),str(HERE/'runtime.c'),'-o',str(target),'-lkernel32'],check=True)
 if not a.qa:
  workspace=HERE.parents[3]
  loader=workspace/'outputs/reconnect-build-20261013/probe/avifil32.dll'
  if not m.get('installed'):shutil.copy2(loader,a.out/'sandbox/avifil32.dll')
 if m.get('installed'):
  config=destination/'plugins.txt';rows=[v for v in config.read_text().splitlines() if not v.lower().strip().startswith('pawsbridges')];config.write_text('\n'.join(rows)+ '\n'+target.name+'\n')
 elif not a.qa:(destination/'plugins.txt').write_text('PawsBridges.dll\n')
 print('BRIDGE_PLUGIN_READY',target)
if __name__=='__main__':main()
