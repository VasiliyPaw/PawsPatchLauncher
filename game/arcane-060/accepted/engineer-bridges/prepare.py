"""Prepare the local bridge build on top of the accepted separate road prototype."""
import argparse,sys,subprocess,json,hashlib,shutil
from pathlib import Path
ROOT=Path(__file__).resolve().parents[2]
p=argparse.ArgumentParser();p.add_argument('--game',type=Path,required=True);p.add_argument('--out',type=Path,required=True);p.add_argument('--models',type=Path,required=True);a=p.parse_args()
subprocess.run([sys.executable,'-B',str(ROOT/'game/engineer-roads/prepare.py'),'--game',str(a.game),'--out',str(a.out)],check=True)
sys.path[:0]=[str(ROOT/'tools'),str(ROOT/'game/lobby-colors')]
from compact_menu import span
from PrepareSplitLanguages import dec
from models import prepare,definitions,construction_effect
prepare(a.models,a.out/'sandbox/probe-data')
for root in (a.out/'locales').iterdir():
 ui=root/'UI/Game/game_interface.tgi';s=dec(ui.read_bytes());start,end=span(s,'PawRoadButton')
 # Bridge button is generated by the stock engineer BuilderComponent pane.
 ui.write_text(s,encoding='utf-16')
 terrain=root/'Terrain/Temperate/temperate_road.tgi'
 s=terrain.read_bytes().decode('utf-16')
 new='''[Terrain Template=WaterTerrain]
{
 IDS = paws_engineer_bridge
 name = "Bridge water"
 base_priority = 104501
 terrain_group = water
 land = true
 water = true
 doodad_frequency = 0
 primary_doodad_frequency = 0
 anim_textures_path_prefix = TemperateWater/WaterFrames%04d.dds
 anim_fps = 10
 color = 0.010, 0.240, 0.320
 [Variation]
 {
  IDS = paws_engineer_bridge01
  name = "Bridge water"
  texture = TemperateWater/TemperateWater01.tga
  texture_width = 8
  texture_height = 8
  terrain_color = 0.000, 0.306, 0.408
  weight = 1
 }
}'''
 terrain.write_text(s+'\n'+new,encoding='utf-16')
 # Append definitions to an already registered stock file. New standalone TGI
 # filenames are not automatically read by the native database loader.
 stock=dec((a.game/'data/Special/Things/thing_visibilityactors.tgi').read_bytes()) if (a.game/'data/Special/Things/thing_visibilityactors.tgi').is_file() else None
 if stock is None:
  from PrepareSplitLanguages import rwd_files
  stock=dec(rwd_files((a.game/'Data.rwd').read_bytes())['Special/Things/thing_visibilityactors.tgi'])
 actors=root/'Special/Things/thing_visibilityactors.tgi';actors.parent.mkdir(parents=True,exist_ok=True)
 actors.write_text(stock+'\n'+definitions(root.name),encoding='utf-16')
 # A single logical entry avoids exposing 112 length/orientation variants.
 # The native placement brush substitutes the actual bank-to-bank variant.
 from PrepareSplitLanguages import rwd_files
 if 'files' not in globals():files=rwd_files((a.game/'Data.rwd').read_bytes())
 for path in ['Units/Human/engineer.tgi','Units/Haroun/caretaker.tgi','Units/Gauri/forge.tgi','Units/Drauga/crafter.tgi','Units/Shadow/nightbringer.tgi','Units/Undead/boneweaver.tgi']:
  text=dec(files[path]);point=text.index('[BuildActor]')
  text=text[:point]+'[BuildActor]\n actor_ids = paws_bridge_wood_site\n\n [BuildActor]\n actor_ids = paws_bridge_stone_site\n\n '+text[point:]
  dest=root/path;dest.parent.mkdir(parents=True,exist_ok=True);dest.write_text(text,encoding='utf-16')
 effects=root/'Effects/construction.tgi';effects.parent.mkdir(parents=True,exist_ok=True)
 effects.write_text(dec(files['Effects/construction.tgi'])+construction_effect(),encoding='utf-16')
fixture=Path(__file__).with_name('fixtures')/'Bridge-ready.RSG'
if fixture.exists():
 dest=a.out/'sandbox/Userdata/Save/Bridge-ready.RSG'
 if not dest.exists():shutil.copy2(fixture,dest)
manifest={str(f.relative_to(a.out)):hashlib.sha256(f.read_bytes()).hexdigest()for f in (a.out/'locales').rglob('*')if f.is_file()}
(a.out/'menu-manifest.json').write_text(json.dumps(manifest,indent=2))
print('Prepared bridge sandbox',a.out)
